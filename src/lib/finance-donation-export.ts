import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

import {
  calcDonationTotals,
  fmtPKR,
  type MonthlyDonationFields,
} from "@/lib/finance";

export interface DonationExportAttachment {
  key: string;
  name?: string;
  url?: string;
}

export interface MonthlyDonationExportInput {
  title?: string;
  month?: string;
  chapterName?: string;
  status?: string;
  fields: MonthlyDonationFields;
  attachments?: DonationExportAttachment[];
  generatedBy?: string;
}

const MARGIN = 14;
const INK = {
  text: [28, 28, 28] as [number, number, number],
  soft: [90, 90, 90] as [number, number, number],
  headerBg: [232, 245, 233] as [number, number, number],
};

function num(v: number | "" | undefined | null): number {
  if (v === "" || v == null || Number.isNaN(Number(v))) return 0;
  return Number(v);
}

function hasSs(attachments: DonationExportAttachment[] | undefined, key: string): string {
  const hit = (attachments || []).find((a) => a.key === key && a.url);
  return hit ? "Yes" : "—";
}

function safeFilePart(s: string) {
  return String(s || "file")
    .replace(/[\\/:*?"<>|]/g, "-")
    .replace(/\s+/g, "_")
    .slice(0, 60);
}

function buildFlatRows(fields: MonthlyDonationFields, attachments?: DonationExportAttachment[]) {
  const rows: Array<{
    level: string;
    name: string;
    amount: number;
    description: string;
    screenshot: string;
  }> = [];

  rows.push({
    level: "BOG Head",
    name: fields.bogHeadName || "—",
    amount: num(fields.bogHeadAmount),
    description: "",
    screenshot: hasSs(attachments, fields.bogHeadSsKey),
  });

  for (const cab of fields.cabinetMembers || []) {
    rows.push({
      level: cab.role ? `Cabinet (${cab.role})` : "Cabinet Member",
      name: cab.name || "—",
      amount: num(cab.amount),
      description: "",
      screenshot: hasSs(attachments, cab.ssKey),
    });
    for (const d of cab.directors || []) {
      rows.push({
        level: "Director",
        name: d.name || "—",
        amount: num(d.amount),
        description: d.description || "",
        screenshot: hasSs(attachments, d.ssKey),
      });
    }
    for (const a of cab.assistantDirectors || []) {
      rows.push({
        level: "Assistant Director",
        name: a.name || "—",
        amount: num(a.amount),
        description: a.description || "",
        screenshot: hasSs(attachments, a.ssKey),
      });
    }
  }

  for (const al of fields.alumni || []) {
    rows.push({
      level: "Alumni",
      name: al.name || "—",
      amount: num(al.amount),
      description: al.description || "",
      screenshot: hasSs(attachments, al.ssKey),
    });
  }

  return rows;
}

export async function buildMonthlyDonationPdf(input: MonthlyDonationExportInput): Promise<{
  blob: Blob;
  filename: string;
}> {
  const fields = {
    ...input.fields,
  };
  const totals = calcDonationTotals(fields);
  const rows = buildFlatRows(fields, input.attachments);

  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  let y = MARGIN;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(...INK.text);
  doc.text(
    `${input.month || "Monthly"} Monthly Donation`,
    MARGIN,
    y,
  );
  y += 7;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(...INK.soft);
  const meta = [
    `Team: ${fields.teamName || "Finance"}`,
    `Chapter: ${input.chapterName || "—"}`,
    `Status: ${input.status || "draft"}`,
  ].join("   ·   ");
  doc.text(meta, MARGIN, y);
  y += 6;
  if (input.title) {
    doc.text(input.title, MARGIN, y);
    y += 6;
  }
  if (input.generatedBy) {
    doc.setFontSize(8);
    doc.text(`Generated by ${input.generatedBy}`, MARGIN, y);
    y += 5;
  }

  autoTable(doc, {
    startY: y,
    head: [["Level", "Name", "Amount (PKR)", "Description", "SS"]],
    body: rows.map((r) => [
      r.level,
      r.name,
      r.amount ? r.amount.toLocaleString("en-PK") : "—",
      r.description || "—",
      r.screenshot,
    ]),
    styles: { fontSize: 8, cellPadding: 2, textColor: INK.text },
    headStyles: {
      fillColor: INK.headerBg,
      textColor: INK.text,
      fontStyle: "bold",
    },
    columnStyles: {
      0: { cellWidth: 36 },
      1: { cellWidth: 45 },
      2: { cellWidth: 28,halign: "right" },
      3: { cellWidth: 46 },
      4: { cellWidth: 14, halign: "center" },
    },
    margin: { left: MARGIN, right: MARGIN },
  });

  // @ts-expect-error jspdf-autotable adds lastAutoTable
  y = (doc.lastAutoTable?.finalY ?? y) + 8;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(...INK.text);
  doc.text("Totals", MARGIN, y);
  y += 5;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  const totalLines = [
    `Alumni total: ${fmtPKR(totals.totalAlumniDonation)}`,
    `BOG head donation: ${fmtPKR(totals.totalBogDonation)}`,
    `Cabinet members donation: ${fmtPKR(totals.totalCabinetDonation)}`,
    `Directors donation: ${fmtPKR(totals.totalDirectorsDonation)}`,
    `Assistant directors donation: ${fmtPKR(totals.totalAdsDonation)}`,
    `Total amount in Finance Account: ${fmtPKR(totals.financeAccountTotal)}`,
  ];
  if (fields.otherAccountName || totals.otherAccountTotal) {
    totalLines.push(
      `Total amount in ${fields.otherAccountName || "other account"}: ${fmtPKR(totals.otherAccountTotal)}`,
    );
  }
  totalLines.push(`Grand Total: ${fmtPKR(totals.grandTotal)}`);

  for (const line of totalLines) {
    if (y > doc.internal.pageSize.getHeight() - 20) {
      doc.addPage();
      y = MARGIN;
    }
    doc.text(line, MARGIN, y);
    y += 5;
  }

  doc.setFontSize(8);
  doc.setTextColor(...INK.soft);
  doc.text(
    `Serve Humanity Finance · ${new Date().toLocaleString()}`,
    MARGIN,
    doc.internal.pageSize.getHeight() - 8,
  );
  doc.text(`Page ${doc.getNumberOfPages()}`, pageW - MARGIN - 20, doc.internal.pageSize.getHeight() - 8);

  const filename = `SH_monthly_donations_${safeFilePart(input.month || "month")}_${safeFilePart(fields.teamName || "Finance")}.pdf`;
  const blob = doc.output("blob");
  return { blob, filename };
}

export async function downloadMonthlyDonationPdf(input: MonthlyDonationExportInput) {
  const { blob, filename } = await buildMonthlyDonationPdf(input);
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
  return { blob, filename };
}
